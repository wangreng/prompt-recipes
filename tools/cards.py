# Builds demos/<demo>/RECIPE.md and the summary table in RESULTS.md from round artifacts.
import json,os,glob
ROOT=os.path.expanduser('~/prompt-recipes'); os.chdir(ROOT+'/demos')
INFO={'gemini_95':('Gemini 95','Retro Windows-95-style desktop with AI apps'),
 'flashcard_maker':('Flashcard Maker','Topic → flashcards generator'),
 'gemini_co_drawing':('Gemini Co-Drawing','Sketch canvas + prompt, Gemini redraws')}
def j(p):
    try: return json.load(open(p))
    except Exception: return None
rows=[]
for d,(name,desc) in INFO.items():
    R=sorted(int(p.split('.r')[-1][:-3]) for p in glob.glob(f'{d}/rounds/prompt.r*.md'))
    R=[r for r in R if os.path.exists(f'{d}/shots/regen-r{r}.png')]
    L=[f'# Prompt recipe: {name}','',f'{desc}.','',
       f'- **Source code:** https://github.com/google-gemini/aistudio-showcase/tree/main/src/{d} (Apache-2.0, copy in `original/`)',
       f'- **In AI Studio:** https://aistudio.google.com/apps/bundled/{d}',
       '- **Viewport:** 1440×900, first screen, no API key (so no generated content is shown)','',
       '## Scores per round','',
       '| Round | Gemini self-score | Codex (GPT) score | Gap | SSIM | Pixel diff | Flag |','|---|---|---|---|---|---|---|']
    best=None
    for r in R:
        g=j(f'{d}/rounds/score.r{r}.json') or {}; c=j(f'{d}/rounds/score-codex.r{r}.json') or {}; m=j(f'{d}/rounds/metrics.r{r}.json') or {}
        gs,cs=g.get('score'),c.get('score'); gap=(gs-cs) if gs is not None and cs is not None else None
        flag=[]
        if m and max([x for x in (gs,cs) if x is not None] or [0])>=85 and m.get('ssim',1)<0.93: flag.append('model high / SSIM low')
        if gap is not None and abs(gap)>=15: flag.append('judges disagree')
        L.append(f"| r{r} | {gs if gs is not None else '–'} | {cs if cs is not None else 'pending'} | {('%+d'%gap) if gap is not None else '–'} | {m.get('ssim','–')} | {m.get('pixel_diff_pct','–')}% | {', '.join(flag) or ''} |")
        key=(cs if cs is not None else -1, m.get('ssim',0))
        if best is None or key>best[0]: best=(key,r)
        rows.append((name,r,gs,cs,gap,m.get('ssim'),m.get('pixel_diff_pct')))
    br=best[1] if best else R[-1]
    L+=['',f'Final recipe = round {br} (highest Codex score, SSIM as tiebreak; falls back to the last round while Codex scores are pending).','',
        '## Screenshots','','| Original | Final regeneration (r%d) |'%br,'|---|---|',
        f'| ![original](shots/original.png) | ![r{br}](shots/regen-r{br}.png) |','',
        'All rounds: '+' · '.join(f'[r{r}](shots/regen-r{r}.png)' for r in R),'',
        '## Final prompt','','```text',open(f'{d}/rounds/prompt.r{br}.md').read().strip(),'```','',
        '## Judge notes (final round)','']
    for who,f in (('Gemini (self)',f'{d}/rounds/score.r{br}.json'),('Codex (GPT)',f'{d}/rounds/score-codex.r{br}.json')):
        x=j(f); L.append(f'- **{who}:** '+(x['notes'] if x else 'pending'))
    L+=['','## Caveats','',
        '- **Source leak:** the reverse-engineering and refine steps read the original source code, so the prompt carries exact strings, sizes and colours a real user would rarely type. High scores show the prompt *reproduces* the app, not that a human would have *written* it.',
        '- **First screen only:** these apps are interactive; generated content, modals and later states are not compared.',
        '- **SSIM on flat UIs:** big plain backgrounds push SSIM up (0.9+ even for visibly different details); read it with the model notes, not alone.',
        '- **Harness:** both original and regen are built with the same esbuild + importmap harness (`tools/shoot.sh`), which mimics AI Studio’s injected script/CSS.','',
        'Prompt history: '+' · '.join(f'[r{r}](rounds/prompt.r{r}.md)' for r in R)+'. Generated code per round in `rounds/regen-rN/`.']
    open(f'{d}/RECIPE.md','w').write('\n'.join(L)+'\n')
T=['| Demo | Round | Gemini self | Codex | Gap | SSIM | Pixel diff |','|---|---|---|---|---|---|---|']
for n,r,g,c,gap,s,p in rows: T.append(f"| {n} | r{r} | {g if g is not None else '–'} | {c if c is not None else 'pending'} | {('%+d'%gap) if gap is not None else '–'} | {s} | {p}% |")
open('../RESULTS.md','w').write('# Results\n\nGenerated by `tools/cards.py` from `demos/*/rounds/*.json`.\n\n'+'\n'.join(T)+'\n')
print('\n'.join(T))
